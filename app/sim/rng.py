"""Arm-independent random streams.

Each named channel (sensor noise, wind, ...) is a Philox generator keyed by
``sha256(seed:channel)``, and values are pre-generated by tick index. So the
noise a flight sees depends only on (scenario seed, tick), never on which arm
is flying or how many decisions it made.
"""

from __future__ import annotations

import hashlib

import numpy as np


def channel_generator(seed: int, channel: str) -> np.random.Generator:
    digest = hashlib.sha256(f"{seed}:{channel}".encode()).digest()
    key = np.frombuffer(digest[:16], dtype=np.uint64)
    return np.random.Generator(np.random.Philox(key=key))


def ou_process(
    gen: np.random.Generator, n: int, dt: float, sigma: float, tau: float
) -> np.ndarray:
    """Exact-discretisation Ornstein-Uhlenbeck path with stationary std ``sigma``."""

    out = np.zeros(n)
    if sigma <= 0.0 or n == 0:
        return out
    a = float(np.exp(-dt / max(tau, 1e-6)))
    b = sigma * float(np.sqrt(1.0 - a * a))
    noise = gen.standard_normal(n)
    x = sigma * float(gen.standard_normal())
    for i in range(n):
        x = a * x + b * noise[i]
        out[i] = x
    return out


__all__ = ["channel_generator", "ou_process"]
